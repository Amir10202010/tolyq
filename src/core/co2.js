//  TOLYQ — УГЛЕРОДНЫЙ СЛЕД
// ---------------------------------------------------------------------
//  Принципиальная асимметрия учёта, и она не ошибка:
//
//  ФУРА  — выброс относим на отправителя ЦЕЛИКОМ, потому что он занял
//          машину один. Полупустая фура едет так же, как полная:
//          гружёная на 40 % фура выбрасывает почти столько же, сколько
//          гружёная на 100 %. Именно это мы и хотим показать.
//
//  ВАГОН — выброс делится между всеми, кто в вагоне, пропорционально
//          массе. Отсюда формула на тонно-километр: отправитель платит
//          углеродом ровно за свои тонны.
//
//  Эта асимметрия — суть экономии: не «поезд чище фуры вообще»,
//  а «делить вагон чище, чем занимать фуру в одиночку».
// =====================================================================

import {
  TRUCK_CO2_KG_PER_KM,
  RAIL_CO2_G_PER_TKM,
  TRANSSHIP_CO2_KG,
  TRUCK_CAP_T,
  TRUCK_CAP_M3,
} from './network.js';

/**
 * Сколько фур нужно, чтобы увезти партию.
 * Ограничение и по массе, и по объёму — лёгкий габаритный груз
 * упирается в кубатуру раньше, чем в тонны.
 * @returns {number} целое >= 1
 */
export function trucksNeeded(tons, volumeM3 = 0) {
  const byMass = tons > 0 ? Math.ceil(tons / TRUCK_CAP_T) : 0;
  const byVol = volumeM3 > 0 ? Math.ceil(volumeM3 / TRUCK_CAP_M3) : 0;
  return Math.max(1, byMass, byVol);
}

/**
 * Выброс автомобильного участка.
 * Считаем по числу занятых машин, а не по тоннам: две фуры на 25 тонн
 * дают вдвое больше выброса, чем одна на 20, — так это и работает.
 * @param {number} km
 * @param {number} tons
 * @param {number} [volumeM3]
 * @returns {number} кг CO2
 */
export function truckCo2Kg(km, tons, volumeM3 = 0) {
  return km * TRUCK_CO2_KG_PER_KM * trucksNeeded(tons, volumeM3);
}

/**
 * Выброс железнодорожного участка, приходящийся на НАШИ тонны.
 * Деление между отправителями заложено в саму размерность г/ткм:
 * сумма долей всех грузов в вагоне равна выбросу вагона.
 * @param {number} km
 * @param {number} tons масса нашей партии
 * @returns {number} кг CO2
 */
export function railCo2Kg(km, tons) {
  return (km * tons * RAIL_CO2_G_PER_TKM) / 1000;
}

/**
 * Выброс операций перегрузки.
 * ОЦЕНКА: 12 кг на операцию — маневровый тепловоз и погрузчик.
 * Точных данных по терминалам РК у нас нет, число намеренно грубое
 * и на итог влияет слабо (единицы килограммов против сотен).
 * @param {number} count число перегрузок на маршруте
 */
export function transshipCo2Kg(count) {
  return count * TRANSSHIP_CO2_KG;
}

/**
 * Выброс одного участка маршрута — единая точка входа для pareto.js.
 * @param {'road'|'rail'} mode
 * @param {number} km
 * @param {number} tons
 * @param {number} [volumeM3]
 */
export function legCo2Kg(mode, km, tons, volumeM3 = 0) {
  return mode === 'road' ? truckCo2Kg(km, tons, volumeM3) : railCo2Kg(km, tons);
}

/**
 * Сколько CO2 экономит перевод партии с фуры на вагон на плече.
 * Отрицательное значение означало бы, что ЖД тут грязнее, — такое
 * возможно на очень тяжёлых партиях, и мы это честно покажем.
 */
export function savingKg(km, tons, volumeM3 = 0) {
  return truckCo2Kg(km, tons, volumeM3) - railCo2Kg(km, tons);
}
