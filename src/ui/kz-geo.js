/**
 * КАСПИЙ. Не отдельный обвод, а тот же самый берег: восточная кромка
 * моря буквально вырезана из государственной границы (участок от
 * туркменского угла до волжской дельты) и замкнута далеко на западе, за
 * пределами кадра. Рисовать Каспий вторым, независимым контуром нельзя:
 * два упрощения одной и той же линии никогда не совпадут, и вдоль всего
 * Мангышлака поползёт белая щель в полпикселя.
 *
 * Зачем он вообще: без воды западная граница — просто зубчатая ломаная,
 * и Актау висит на ней неизвестно почему. С водой сразу видно, что это
 * порт на берегу моря, а Мангышлакский полуостров делает силуэт страны
 * узнаваемым с одного взгляда.
 *
 * Замыкающие точки вынесены ДАЛЕКО за рамку — до 34° долготы при левом
 * крае кадра около 46,5° и до 26° широты при нижнем крае 40,6°. Запас
 * тут не роскошь: масштаб зависит от ширины панели, и на узкой колонке
 * поля сжимаются вместе с ним. Замыкание, которого хватало на широком
 * экране, на телефоне въезжало бы в кадр прямой линией — а прямая линия
 * поперёк воды сразу читается как ошибка отрисовки, а не как берег.
 */
